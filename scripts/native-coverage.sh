#!/usr/bin/env bash
# Mixed Rust/C coverage: use a Clang with the same LLVM major as nightly rustc.
set -euo pipefail
cd "$(dirname "$0")/.."
# Old instrumented objects can add stale maps even after profraw-only clean.
# Every invocation gets a new build tree; previous evidence is retained.
coverage_root=$(python3 -c 'from pathlib import Path; import sys; print(Path(sys.argv[1]).resolve())' "${CARGO_TARGET_DIR:-$PWD/target/native-cov}")
mkdir -p "$coverage_root"
run_directory=$(mktemp -d "$coverage_root/run-XXXXXXXX")
export CARGO_TARGET_DIR="$run_directory/build"
export CARGO_LLVM_COV_TARGET_DIR="$CARGO_TARGET_DIR"
export CARGO_LLVM_COV_BUILD_DIR="$CARGO_TARGET_DIR"
python3 scripts/coverage-snapshot.py "$PWD" > "$run_directory/source-before.json"
# Invoked indirectly by the EXIT trap; verified by provenance regression tests.
# shellcheck disable=SC2329
finish_coverage_run() {
  final_status=$?
  trap - EXIT
  python3 scripts/coverage-snapshot.py "$PWD" > "$run_directory/source-after.json" || final_status=1
  python3 scripts/coverage-run-manifest.py "$run_directory" "$coverage_root" "$final_status" \
    --artifact coverage.json --artifact coverage-native-first.json --artifact c-coverage.json \
    --artifact export-diagnostics.json --artifact flags.json || { if [[ "$final_status" == 0 ]]; then final_status=1; fi; }
  exit "$final_status"
}
trap finish_coverage_run EXIT
export CC="${CC:-clang}"
# bindgen discovers a Clang executable independently of cc-rs. Its resource
# headers must match the loaded libclang, especially for AArch64 NEON builtins.
if [[ -z "${CLANG_PATH:-}" ]]; then
  CLANG_PATH=$(command -v "$CC")
  export CLANG_PATH
fi
if [[ -z "${LIBCLANG_PATH:-}" ]]; then
  resource_directory=$("$CC" --print-resource-dir)
  LIBCLANG_PATH=$(python3 - "$resource_directory" <<'PYCLANG'
from pathlib import Path
import sys
library = Path(sys.argv[1]).resolve().parents[1]
if not any(library.glob('libclang*.so*')) and not any(library.glob('libclang*.dylib')):
    sys.exit('Matching libclang missing next to compiler resource directory: ' + str(library))
print(library)
PYCLANG
)
  export LIBCLANG_PATH
fi
export PROFILER_C_COVERAGE=1
export PROFILER_C_UNIT_BOUNDARIES=1
export PROFILER_SAMPLING_UNIT=1
export PROFILER_ADAPTER_CONTRACT_TEST=1
coverage_toolchain="${PROFILER_COVERAGE_TOOLCHAIN:-nightly}"
export PROFILER_COVERAGE_TOOLCHAIN="$coverage_toolchain"
rustc +"$coverage_toolchain" -vV > "$run_directory/rustc.txt"
"$CC" --version > "$run_directory/cc.txt"
# Coverage counters themselves must not race the tested concurrent code.
CARGO_ENCODED_RUSTFLAGS="$(python3 - <<'PYFLAGS'
import os, shlex
flags = os.environ.get('CARGO_ENCODED_RUSTFLAGS')
flags = flags.split(chr(31)) if flags else shlex.split(os.environ.get('RUSTFLAGS', ''))
print(chr(31).join(flags + ['-C', 'llvm-args=--instrprof-atomic-counter-update-all']))
PYFLAGS
)"
export CARGO_ENCODED_RUSTFLAGS
# show-env establishes profile names with process/module identifiers for PHP children.
coverage_env="$run_directory/coverage-env.sh"
cargo +"$coverage_toolchain" llvm-cov show-env --sh --branch > "$coverage_env"
# Generated by the trusted cargo-llvm-cov CLI above; retained as a run artifact.
# shellcheck source=/dev/null
source "$coverage_env"
python3 - "$run_directory/flags.json" <<'PYFLAGS'
import json, os, sys
names = ('CC', 'CLANG_PATH', 'LIBCLANG_PATH', 'CARGO_ENCODED_RUSTFLAGS', '__CARGO_LLVM_COV_RUSTC_WRAPPER_RUSTFLAGS',
         'PROFILER_C_COVERAGE', 'PROFILER_C_UNIT_BOUNDARIES', 'PROFILER_SAMPLING_UNIT',
         'PROFILER_ADAPTER_CONTRACT_TEST')
with open(sys.argv[1], 'w') as output:
    json.dump({name: os.environ.get(name) for name in names}, output, indent=2)
    output.write(chr(10))
PYFLAGS
cargo +"$coverage_toolchain" test -p profiler-core --message-format=json > "$run_directory/core-tests.jsonl"
# The standalone Rust unit binary has no Zend host. Private C transports retain
# Zend functions through their instrumentation hooks; execute those transports
# in the genuine PHP-loaded DSO below, while retaining every pure unit test here.
env -u PROFILER_C_UNIT_BOUNDARIES -u PROFILER_SAMPLING_UNIT \
  cargo +"$coverage_toolchain" test -p php-profiler --lib --message-format=json > "$run_directory/adapter-tests.jsonl"
cargo +"$coverage_toolchain" build -p php-profiler --lib
suffix=so
if [[ "$OSTYPE" == darwin* ]]; then suffix=dylib; fi
export PROFILER_EXTENSION="$CARGO_LLVM_COV_TARGET_DIR/debug/libphp_profiler.$suffix"
if [[ "$OSTYPE" != darwin* ]]; then
  source scripts/link-native-faults.sh
fi
scripts/php-tests.sh
scripts/native-fault-tests.sh
python3 scripts/native-bailout-tests.py
PROFILER_SAMPLING_EXTENSION="$PROFILER_EXTENSION" python3 scripts/sampling-controller-tests.py
if [[ "$OSTYPE" != darwin* ]]; then
  php -n -d "extension=$PROFILER_EXTENSION" tests/native/c-boundaries.php
fi
PROFILER_CONTRACT_EXTENSION="$PROFILER_EXTENSION" python3 scripts/adapter-contract-tests.py
python3 scripts/test-report-oom.py
cargo +"$coverage_toolchain" llvm-cov report --json --output-path "$run_directory/coverage.json"
# cargo-llvm-cov exports Rust coverage; explicitly include the instrumented C bridge
# in a second export so the release gate cannot mistake Rust-only coverage for all code.
llvm_bin="$(rustc +"$coverage_toolchain" --print sysroot)/lib/rustlib/$(rustc +"$coverage_toolchain" -vV | sed -n 's/^host: //p')/bin"
profile_data=$(python3 - "$CARGO_LLVM_COV_TARGET_DIR" <<'PYPROFILE'
from pathlib import Path
import sys
profiles = list(Path(sys.argv[1]).glob('*.profdata'))
if len(profiles) != 1:
    sys.exit(f'Expected one fresh merged profile, found {len(profiles)}')
print(profiles[0].resolve())
PYPROFILE
)
python3 - "$llvm_bin/llvm-cov" "$PROFILER_EXTENSION" "$profile_data" "$run_directory/c-coverage.json" <<'PYCEXPORT'
from pathlib import Path
import subprocess, sys
sys.path.insert(0, 'scripts')
from runtime_sources import runtime_sources
with open(sys.argv[4], 'w') as output:
    subprocess.run([sys.argv[1], 'export', sys.argv[2], '-instr-profile=' + sys.argv[3],
                    *map(str, sorted(runtime_sources(Path.cwd(), 'c')))], check=True, stdout=output)
PYCEXPORT
# Put the executing native DSO first. Reversing this order makes llvm-cov
# choose zero-count unit-test maps for identically named exported C callbacks.
python3 scripts/export-native-coverage.py "$llvm_bin/llvm-cov" "$run_directory" "$PROFILER_EXTENSION" "$profile_data"
result=0
python3 scripts/check-coverage.py "$run_directory/coverage-native-first.json" --workspace-root "$PWD" --language rust || result=1
# The C LLVM export is retained as a diagnostic: setjmp returns are misattributed.
# All C source is independently gated by scripts/clang-gcov.sh with raw edge counters.
exit "$result"
