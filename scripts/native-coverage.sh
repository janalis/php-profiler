#!/usr/bin/env bash
# Mixed Rust/C coverage: use a Clang with the same LLVM major as nightly rustc.
set -euo pipefail
cd "$(dirname "$0")/.."
# shellcheck source=scripts/rustflags.sh
source scripts/rustflags.sh
# Old instrumented objects can add stale maps even after profraw-only clean.
# Every invocation gets a new build tree; previous evidence is retained.
mkdir -p "${CARGO_TARGET_DIR:-$PWD/target/native-cov}"
coverage_root=$(cd "${CARGO_TARGET_DIR:-$PWD/target/native-cov}" && pwd -P)
run_directory=$(mktemp -d "$coverage_root/run-XXXXXXXX")
export CARGO_TARGET_DIR="$run_directory/build"
export CARGO_LLVM_COV_TARGET_DIR="$CARGO_TARGET_DIR"
export CARGO_LLVM_COV_BUILD_DIR="$CARGO_TARGET_DIR"
scripts/php-tool.sh scripts/coverage-snapshot.php "$PWD" > "$run_directory/source-before.json"
# Invoked indirectly by the EXIT trap; verified by provenance regression tests.
# shellcheck disable=SC2329
finish_coverage_run() {
  final_status=$?
  trap - EXIT
  scripts/php-tool.sh scripts/coverage-snapshot.php "$PWD" > "$run_directory/source-after.json" || final_status=1
  scripts/php-tool.sh scripts/coverage-run-manifest.php "$run_directory" "$coverage_root" "$final_status" \
    --artifact coverage.json --artifact coverage-native-first.json --artifact c-coverage.json \
    --artifact export-diagnostics.json --artifact flags.json || { if [[ "$final_status" == 0 ]]; then final_status=1; fi; }
  exit "$final_status"
}
trap finish_coverage_run EXIT
export CC="${CC:-clang}"
coverage_toolchain="${PROFILER_COVERAGE_TOOLCHAIN:-nightly}"
export PROFILER_COVERAGE_TOOLCHAIN="$coverage_toolchain"
# Compiler-rt profile structures differ across LLVM majors. A mismatched C
# runtime can crash in profile finalization even when ordinary execution passes.
scripts/php-tool.sh scripts/coverage-toolchain.php "$CC" "$coverage_toolchain"
# bindgen discovers a Clang executable independently of cc-rs. Its resource
# headers must match the loaded libclang, especially for AArch64 NEON builtins.
if [[ -z "${CLANG_PATH:-}" ]]; then
  CLANG_PATH=$(command -v "$CC")
  export CLANG_PATH
fi
if [[ -z "${LIBCLANG_PATH:-}" ]]; then
  resource_directory=$("$CC" --print-resource-dir)
  LIBCLANG_PATH=$(cd -P "$resource_directory" && cd -P ../.. && pwd -P)
  if ! compgen -G "$LIBCLANG_PATH/libclang*.so*" > /dev/null && ! compgen -G "$LIBCLANG_PATH/libclang*.dylib" > /dev/null; then
    echo "Matching libclang missing next to compiler resource directory: $LIBCLANG_PATH" >&2
    exit 1
  fi
  export LIBCLANG_PATH
fi
export PROFILER_C_COVERAGE=1
export PROFILER_C_UNIT_BOUNDARIES=1
export PROFILER_SAMPLING_UNIT=1
export PROFILER_ADAPTER_CONTRACT_TEST=1
rustc +"$coverage_toolchain" -vV > "$run_directory/rustc.txt"
"$CC" --version > "$run_directory/cc.txt"
# Coverage counters themselves must not race the tested concurrent code.
append_rustflags -C llvm-args=--instrprof-atomic-counter-update-all
# show-env establishes profile names with process/module identifiers for PHP children.
coverage_env="$run_directory/coverage-env.sh"
cargo +"$coverage_toolchain" llvm-cov show-env --sh --branch > "$coverage_env"
# Generated by the trusted cargo-llvm-cov CLI above; retained as a run artifact.
# shellcheck source=/dev/null
source "$coverage_env"
scripts/php-tool.sh scripts/environment-receipt.php "$run_directory/flags.json" \
  CC CLANG_PATH LIBCLANG_PATH CARGO_ENCODED_RUSTFLAGS __CARGO_LLVM_COV_RUSTC_WRAPPER_RUSTFLAGS \
  PROFILER_C_COVERAGE PROFILER_C_UNIT_BOUNDARIES PROFILER_SAMPLING_UNIT PROFILER_ADAPTER_CONTRACT_TEST
export LLVM_PROFILE_FILE="$CARGO_LLVM_COV_TARGET_DIR/core-%p-%16m.profraw"
cargo +"$coverage_toolchain" test -p profiler-core --message-format=json > "$run_directory/core-tests.jsonl"
# The standalone Rust unit binary has no Zend host. Private C transports retain
# Zend functions through their instrumentation hooks; execute those transports
# in the genuine PHP-loaded DSO below, while retaining every pure unit test here.
export LLVM_PROFILE_FILE="$CARGO_LLVM_COV_TARGET_DIR/adapter-%p-%16m.profraw"
env -u PROFILER_C_UNIT_BOUNDARIES -u PROFILER_SAMPLING_UNIT \
  cargo +"$coverage_toolchain" test -p php-profiler --lib --message-format=json > "$run_directory/adapter-tests.jsonl"
export LLVM_PROFILE_FILE="$CARGO_LLVM_COV_TARGET_DIR/native-%p-%16m.profraw"
cargo +"$coverage_toolchain" build -p php-profiler --lib
suffix=so
if [[ "$OSTYPE" == darwin* ]]; then suffix=dylib; fi
export PROFILER_EXTENSION="$CARGO_LLVM_COV_TARGET_DIR/debug/libphp_profiler.$suffix"
if [[ "$OSTYPE" != darwin* ]]; then
  source scripts/link-native-faults.sh
fi
scripts/php-tests.sh
scripts/native-fault-tests.sh
scripts/php-tool.sh scripts/native-bailout-tests.php
PROFILER_SAMPLING_EXTENSION="$PROFILER_EXTENSION" scripts/php-tool.sh scripts/sampling-controller-tests.php
if [[ "$OSTYPE" != darwin* ]]; then
  php -n -d "extension=$PROFILER_EXTENSION" tests/native/c-boundaries.php
fi
PROFILER_CONTRACT_EXTENSION="$PROFILER_EXTENSION" scripts/php-tool.sh scripts/adapter-contract-tests.php
scripts/php-tool.sh scripts/test-report-oom.php
cargo +"$coverage_toolchain" llvm-cov report --json --output-path "$run_directory/coverage.json"
# cargo-llvm-cov exports Rust coverage; explicitly include the instrumented C bridge
# in a second export so the release gate cannot mistake Rust-only coverage for all code.
llvm_bin="$(rustc +"$coverage_toolchain" --print sysroot)/lib/rustlib/$(rustc +"$coverage_toolchain" -vV | sed -n 's/^host: //p')/bin"
profiles=()
while IFS= read -r -d '' profile; do profiles+=("$profile"); done \
  < <(find "$CARGO_LLVM_COV_TARGET_DIR" -mindepth 1 -maxdepth 1 -name '*.profdata' -print0)
if [[ ${#profiles[@]} != 1 ]]; then
  echo "Expected one fresh merged profile, found ${#profiles[@]}" >&2
  exit 1
fi
profile_data=$(cd -P "$(dirname "${profiles[0]}")" && printf '%s/%s' "$(pwd -P)" "$(basename "${profiles[0]}")")
c_sources=()
while IFS= read -r source; do c_sources+=("$source"); done < <(scripts/php-tool.sh scripts/runtime-sources.php "$PWD" c)
if [[ ${#c_sources[@]} == 0 ]]; then
  echo 'No runtime C sources found' >&2
  exit 1
fi
"$llvm_bin/llvm-cov" export "$PROFILER_EXTENSION" "-instr-profile=$profile_data" "${c_sources[@]}" > "$run_directory/c-coverage.json"
# Export each actual execution cohort against only its own recorded profiles.
# Unmangled callbacks in standalone tests and PHP DSOs have different map hashes.
scripts/php-tool.sh scripts/export-native-coverage.php "$llvm_bin/llvm-cov" "$run_directory" "$PROFILER_EXTENSION" "$profile_data"
result=0
scripts/php-tool.sh scripts/check-coverage.php "$run_directory/coverage-native-first.json" --workspace-root "$PWD" --language rust || result=1
# The C LLVM export is retained as a diagnostic: setjmp returns are misattributed.
# All C source is independently gated by scripts/clang-gcov.sh with raw edge counters.
exit "$result"
